-- Hush Milestone 4: move all durable server state into managed PostgreSQL.
-- This file is intentionally executable and contains the real schema used by
-- the application. It is applied idempotently at cloud-service startup.

CREATE TABLE IF NOT EXISTS schema_migrations (
    version       TEXT PRIMARY KEY,
    applied_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts            TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    raw           TEXT NOT NULL,
    clean         TEXT NOT NULL,
    level         VARCHAR(16) NOT NULL DEFAULT 'light'
                  CHECK (level IN ('none', 'light', 'medium', 'high')),
    app           VARCHAR(200),
    client_id     VARCHAR(128),
    status        VARCHAR(16) NOT NULL DEFAULT 'final'
                  CHECK (status IN ('pending', 'final', 'failed')),
    words         INTEGER NOT NULL DEFAULT 0 CHECK (words >= 0)
);

CREATE INDEX IF NOT EXISTS entries_ts_idx ON entries (ts DESC);
CREATE INDEX IF NOT EXISTS entries_client_ts_idx ON entries (client_id, ts DESC);

CREATE TABLE IF NOT EXISTS uploads (
    id                UUID PRIMARY KEY,
    bucket            TEXT NOT NULL,
    object_name       TEXT NOT NULL UNIQUE,
    original_filename TEXT NOT NULL,
    content_type      VARCHAR(100) NOT NULL DEFAULT 'audio/wav',
    size_bytes        BIGINT NOT NULL CHECK (size_bytes >= 0),
    status            VARCHAR(16) NOT NULL DEFAULT 'pending'
                      CHECK (status IN ('pending', 'stored', 'completed', 'failed')),
    error_message     TEXT,
    history_id        BIGINT REFERENCES entries(id) ON DELETE SET NULL,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at      TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS uploads_created_at_idx ON uploads (created_at DESC);
CREATE INDEX IF NOT EXISTS uploads_history_id_idx ON uploads (history_id);

CREATE TABLE IF NOT EXISTS snippets (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                TEXT NOT NULL,
    shortcut            TEXT NOT NULL,
    normalized_shortcut TEXT NOT NULL UNIQUE,
    expanded_text       TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(btrim(name)) > 0),
    CHECK (length(btrim(shortcut)) > 0),
    CHECK (length(btrim(expanded_text)) > 0)
);

CREATE TABLE IF NOT EXISTS app_settings (
    key         TEXT PRIMARY KEY,
    value       JSONB NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
